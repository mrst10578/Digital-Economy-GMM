"""Independent archived-output QA for Phase-B exploratory static TWFE results.

Never equate output reproducibility with causal identification; no Stata model
or new external WDI records are generated by this QA.
"""
from pathlib import Path
import csv
import hashlib
import math

ROOT=Path(__file__).resolve().parents[3]
COEFS=ROOT/"evidence/extended/phase2_wdi_twfe_840_four_model_coefficients.csv"
COMPS=ROOT/"evidence/extended/phase2_wdi_twfe_840_digital_comparison.csv"
ORIG=ROOT/"data/raw/Balanced_Panel_Data.xlsx"
SHA="474d5525a37ecfbb424c9dd25d832a9ffa6eed1942bd4f4900454204810d215b"
DIGITAL={"Internet","Broadband","ICT_Exports"}
BASE=DIGITAL|{"Unemployment","Inflation","RnD"}
ADDED={"FDI_inflow_percent_GDP","ICT_imports_percent_goods"}
OUTCOMES={"Growth","ln_Productivity"}
SPECS={"baseline_matched_840","expanded_matched_840"}

def rows(path):
    with path.open(encoding="utf-8",newline="") as f:return list(csv.DictReader(f))

def main():
    assert hashlib.sha256(ORIG.read_bytes()).hexdigest()==SHA
    r=rows(COEFS); c=rows(COMPS)
    assert len(r)==28 and len(c)==6
    index={}
    for row in r:
        y=row["dependent"]; s=row["specification"]; term=row["coefficient_name"]
        assert y in OUTCOMES and s in SPECS
        assert term in BASE | (ADDED if s=="expanded_matched_840" else set())
        assert (y,s,term) not in index
        index[(y,s,term)]=row
        assert int(row["n_obs"])==840 and int(row["n_countries"])==47
        assert row["year_range"]=="2005-2022"
        assert row["entity_and_year_FE"]=="True" and row["causal_inference"]=="False"
        assert row["covariance"]=="Driscoll-Kraay Bartlett bandwidth 2"
        for k in ["coefficient","robust_std_error","p_value","CI95_lower","CI95_upper"]:
            assert math.isfinite(float(row[k])),(row,k)
        assert float(row["robust_std_error"])>0
        assert 0<=float(row["p_value"])<=1
        assert float(row["CI95_lower"])<float(row["coefficient"])<float(row["CI95_upper"])
    for y in OUTCOMES:
        assert {term for yy,s,term in index if yy==y and s=="baseline_matched_840"}==BASE
        assert {term for yy,s,term in index if yy==y and s=="expanded_matched_840"}==BASE | ADDED
    for row in c:
        key=(row["dependent"],row["term"])
        assert key[0] in OUTCOMES and key[1] in DIGITAL
        assert row["same_840_observations"]=="True" and row["causal"]=="False"
        for k,prefix in (("baseline_beta","baseline_matched_840"),
                         ("expanded_beta","expanded_matched_840")):
            assert abs(float(row[k])-float(index[key[0],prefix,key[1]]["coefficient"]))<1e-12
        assert abs(float(row["beta_change"])-(float(row["expanded_beta"])-float(row["baseline_beta"])))<1e-12
    print("ARCHIVED_TWFE_QA_PASS 28 coefficient rows, 6 same-sample digital contrasts, 47 countries, 840 rows each")
    print("CAUSAL_VALIDATION=NONE; PROFESSOR_SYSTEM_GMM=UNMODIFIED")

if __name__=="__main__":main()
